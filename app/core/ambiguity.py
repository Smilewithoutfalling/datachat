"""口径完整性的字面判定：这段问句到底说清了「算什么、怎么算」没有（2026-11-13）。

## 为什么要有代码判定

workflow 的 planner 现在能反问（口径不明时输出 `CLARIFY:` 短路到 summarizer）。但实测
发现**模型判不准**：让它自己决定「该不该问」，16 道明确给了指标和聚合方式的题里
（「总销售额是多少」「平均库存是多少」「月度产品销量变化情况」…）有 5 道被反问，
误判率 31%。原因不难理解 —— 模型被训练成"拿不准就问"，而这类题的正确行为是
"选主流口径算、分歧写进结论"。

所以责任这么分：

  代码判「能算的」  题面同时命中指标词和聚合词 → 直接正常规划，不给模型反问的机会
  模型判「可能不能算的」  没命中 → 交回给 planner 按上下文判断（它能看到表结构和历史）

边界很清楚：词表只用来**放行**，不用来**判定该问**。漏放行的代价是模型多问一次，
错放行的代价是一道该说的题被反问 —— 前者用户能立刻纠正，后者是答非所问。

## 词表的来源与它的天花板

词取自 `data/eval/*.dict.csv` 的字段说明，只保留**能量出数**的名词；城市 / 渠道 / 品类 /
部门 / 日期这类纯维度不算（它们能 group by，但本身不是一个量）。

天花板是真实的：中文里「销售总额」不含「销售额」，词序一变就漏。所以这里的命中是
充分条件，不是必要条件 —— 没命中不代表不能算，只是这条捷径走不通，交回模型。
2026-11-13 用 202 道评测题核过：命中放行的题里没有一道是该反问的（见
tests/test_clarify_spec.py::test_missing_items_is_a_validator_not_a_classifier 的反向断言）。
"""
import re

# 可计量的量。「买几件 / 多少件」单列：中文里「几件」既是算子（多少）又暗含指标（件数），
# 光靠「件数」收不到「平均每单买几件」。
METRIC_MARKERS = re.compile(
    r"金额|单价|价格|标价|成本|利润|毛利|销量|件数|买几件|多少件|数量|库存|到货"
    r"|工资|月薪|年薪|薪资|奖金|绩效|折扣|退款|销售额|营收|收入|客单价|复购率|流失率"
    r"|占比|比重|比例|比率|行数|条数|人数|员工|天数|司龄|年龄|评分|分数|时长|周转"
    r"|明细|记录|清单"
)

# 聚合 / 统计算子。注意不含「最好 / 表现」这类**没有落点**的评语 ——
# 它们必须配一个指标才有意义（「哪个品类最好」说不出是按金额还是按件数）。
# 「最高 / 最低」是选择算子，与「最大 / 最小」同类：配上「销量」就能算，所以收。
OPERATOR_MARKERS = re.compile(
    r"总|合计|求和|平均|均值|中位数|最大|最小|最多|最少|最高|最低|最贵|最便宜"
    r"|占比|比重|比率|数量|多少|几个|几件|几条|几位|排名|排序|分布|趋势|走势|变化"
    r"|增长|增速|涨幅|环比|同比|交叉表|标准差|方差|去重|统计|列出|找出|所有|全部"
    r"|每条|逐条|明细"
)


def answerable_by_terms(question: str) -> bool:
    """题面同时给了指标和聚合方式 —— 不必问，直接算。

    只做放行，不做否定：返回 False 只说明"这条捷径不适用"，不等于该澄清。
    """
    return bool(METRIC_MARKERS.search(question)) and bool(OPERATOR_MARKERS.search(question))


# ---------------------------------------------------------------------------
# 第二道闸门（2026-11-13 晚）：这三类不能反问
#
# 上线第一版后跑全量，31 处反问里有 28 处是多轮题的**中间轮**。回头看，判据本身没错
# （那些句子确实缺指标），错在**前提**：它假设输入一定是个"要答案的问句"。
#
#   「那 S02 呢？」                    上一轮定过口径，这半句只是指代
#   「只看 2024 年 3 月的订单，去重」  在设前提，用户下一句才说要看什么
#
# 前者只要有「本轮之前有轮次」这个事实就能拦（planner 看不到它，得从 service 传）；
# 后者是**祈使句**，整句在改范围、没索取结果，反问它等于把用户的话打断。
#
# 判据顺序：先看有没有强疑问标记（在提问）→ 再看是不是前提设定（在改范围）→ 都不是才认。
# ---------------------------------------------------------------------------

# 可行性询问：「订单表里能算出毛利率吗」问的不是口径，是这张表有没有那个东西。
# 归 planner 的 A 类（拒答）还是 B 类（反问）？都不是 —— 它该先回答"能不能"，
# 而这件事由表结构决定，planner 看得到。让它走澄清会把一个可以确定回答的
# 「没有成本字段」拖成一句「您想怎么定义毛利」，那是把事实问题当成了偏好问题。
FEASIBILITY_MARKS = re.compile(
    r"能算出|能不能算|可以算吗|算得出来吗|有没有.{0,10}(字段|数据|记录)|表里有|数据里有"
)

# 评价式问法：问的是「好不好 / 怎么样」，不是「是多少」。这类**就算给了范围也该反问** ——
# 「只看华南地区，销售额怎么样？」有前提、有指标，但「怎么样」一个字都没指定怎么给。
# 反过来，「只看已完成的订单，这样的订单有多少笔？」有前提、问的是多少，能算。
EVALUATIVE_MARKS = re.compile(
    r"怎么样|怎样|如何|高不高|低不低|好不好|多吗|多不多|正常吗|合理吗|表现"
    r"|情况|水平|健康吗|有问题吗"
)

# 前提设定语：整句在改范围 / 改筛选 / 改口径，不索取结果。
# 「只看…」「排除…」「换成…」「重新算」都是多轮里先立规矩的写法，后面那轮才问数。
PREMISE_MARKS = re.compile(
    r"只看|仅看|限定|只要|排除|去掉|剔除|不算|加进来|也算|算上|换成|改成"
    r"|再看|再查|其中|其他不变|其余不变|口径不变|重新算|再算一遍|拆开|按.{1,8}拆"
)


def may_clarify(question: str, followup: bool = False) -> bool:
    """planner 这次反问算不算数。False 时把 CLARIFY 丢掉、照常走完整链路。

    ## followup 这一条的效力范围（别读错）

    `followup` 是「本轮之前有轮次」，由 service 从 `mc.followup` 取。**但产品的 workflow
    收不到 history** —— `app/server/app.py` 明写 `history = turn_history(...) if agent ==
    "react" else None`，所以产品里 workflow 的 followup 恒为 False，这一条不生效。

    它在评测里才生效：runner 一律传 history，workflow 收下就丢（见 docs/eval/LEDGER.md:224
    记的坑）。所以第 1 条是**对齐评测口径**，不是产品行为改进 —— 产品里 workflow 多轮本来就
    没有上文，这时候反问是对的（没有 S02 是什么，问一句「您想看 S02 的哪方面」是诚实的）。

    真正改变产品行为的是第 2~5 条：用户在产品里说「只看 2024 年 3 月的订单」，不该被反问。

    顺序是有讲究的，换了就错：
      1. 有上文 → 不反问（评测口径；产品里恒不触发）
      2. 可行性询问（"能算出…吗"）→ 不反问。先回答有没有，不是问你想怎么算
      3. 评价式（"怎么样 / 高不高"）→ 反问。即使给了范围也问，因为「怎么给」没定
      4. 有前提词（"只看 / 排除 / 换成"）→ 不反问。用户在立规矩，下一句才要数
      5. 其余（"帮我看看这批数据"）→ 反问，连对象都没指认
    """
    if followup:
        return False
    q = question or ""
    if FEASIBILITY_MARKS.search(q):
        return False
    if EVALUATIVE_MARKS.search(q):
        return True
    return not PREMISE_MARKS.search(q)
