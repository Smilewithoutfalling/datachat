@pytest.mark.parametrize("cid,answer", sorted(CLEAN.items()))
def test_clean_refusals_are_not_flagged(cid, answer):
    """干净拒答必须全部放行。误杀的代价是逼模型连"为什么答不了"都不敢解释。"""
    assert refusal_leak(answer) == (None, ""), f"{cid} 被误判为越界"


def test_comparative_word_alone_does_not_fail():
    """"最高"在合法拒答里出现过（inv_021），所以它只能记录不能判错。

    这条同时是对"阈值改小"的护栏：把门槛降到 1 之前，先看 inv_021 会不会被误杀。
    """
    assert refusal_leak("无法回答：表中没有单价，只能给出销量最高的 SKU。") == (None, "")


