@pytest.mark.parametrize("answer,expect", [
    ("无法回答：数据中没有该字段。", None),
    ("无法回答：数据中没有该字段，缺失率 100%。", None),                     # 1 个：可能只是顺带交代
    ("无法回答：数据中没有该字段；绩效 C 22.4%，高于 A 的 14.7%。", "quantified"),  # 2 个
    ("无法回答：没有该字段。A 组 12%，B 组 13%，C 组 14%。", "quantified"),
])
def test_percentage_threshold(answer, expect):
    assert refusal_leak(answer)[0] == expect


def test_percent_needs_to_be_attached_to_a_number():
    """`%` 单独出现、或"百分比"这种词，不算量化。"""
    assert refusal_leak("无法回答：表中没有该字段，无法给出百分比。") == (None, "")
    assert refusal_leak("无法回答：没有该字段。占比 % % 两个符号不算。") == (None, "")


